import { useState } from 'react'
import { ChevronDown, Copy, X } from 'lucide-react'
import { findings } from '../../data/demoData'
import { useApp } from '../../state'
import { SeverityBadge, SourceBadge, useToast } from '../ui'

export default function FindingDrawer() {
  const { findingId, openFinding } = useApp()
  const toast = useToast()
  const [why, setWhy] = useState(true)
  const f = findings.find(x => x.id === findingId)
  if (!f) return null
  const ai = f.source === 'ai'
  const copy = async () => {
    const text = [`${f.id}: ${f.title}`, `Severity: ${f.severity}`, `Source: ${ai ? 'AI suggestion (unverified)' : `${f.tool} ${f.ruleId}`}`,
      `Location: ${f.filePath}:${f.lineNumber}`, `Next step: ${f.suggestedAction}`, '(Demonstration data)'].join('\n')
    try { await navigator.clipboard.writeText(text); toast('Finding details copied.') } catch { toast('Copy failed. Clipboard access was blocked.', 'err') }
  }
  return <div className="fixed inset-0 z-40 flex justify-end bg-black/50" onClick={() => openFinding(null)}>
    <aside role="dialog" aria-modal="true" aria-label={`Finding ${f.id}`} className="h-full w-full max-w-3xl overflow-auto border-l border-line bg-surf" onClick={e => e.stopPropagation()}>
      <div className="sticky top-0 flex items-center gap-2 border-b border-line bg-surf px-4 py-3">
        <h2 className="flex-1 font-semibold">{f.title}</h2>
        <button className="btn" onClick={copy}><Copy size={14} aria-hidden />Copy finding details</button>
        <button className="icon-btn" aria-label="Close finding" autoFocus onClick={() => openFinding(null)}><X size={16} /></button>
      </div>
      <div className="grid gap-4 p-4 md:grid-cols-[240px_1fr]">
        <dl className="space-y-3 text-sm">
          <div><dt className="text-mute">Severity</dt><dd className="mt-1"><SeverityBadge severity={f.severity} /></dd></div>
          <div><dt className="text-mute">Detection source</dt><dd className="mt-1"><SourceBadge source={f.source} tool={f.tool} /></dd></div>
          <div><dt className="text-mute">Rule</dt><dd className="mono">{f.ruleId ?? 'None (generated)'}</dd></div>
          <div><dt className="text-mute">Location</dt><dd className="mono break-all">{f.filePath}:{f.lineNumber}</dd></div>
          <div><dt className="text-mute">Verification</dt><dd>{f.verification === 'tool-reported' ? 'Reported by tool. Not independently reproduced.' : 'Awaiting verification'}</dd></div>
        </dl>
        <div className="min-w-0 space-y-4">
          <figure className="overflow-auto rounded border border-line bg-bg">
            <figcaption className="mono border-b border-line px-3 py-1 text-xs text-mute">{f.filePath}</figcaption>
            <pre className="mono py-2 text-[13px]">{f.evidence.code.map((l, i) => {
              const n = f.evidence.startLine + i, hit = n === f.lineNumber
              return <div key={n} className={`flex ${hit ? 'bg-err/10' : ''}`}><span className="w-12 shrink-0 select-none pr-3 text-right text-mute">{n}</span><code className="whitespace-pre">{l}</code></div>
            })}</pre>
          </figure>
          <p>{f.description}</p>
          <div><h3 className="font-medium">Recommended next step</h3><p className="text-sub">{f.suggestedAction}</p></div>
          <div className="rounded border border-line">
            <button className="flex w-full items-center justify-between px-3 py-2 font-medium" aria-expanded={why} onClick={() => setWhy(w => !w)}>Why was this flagged?<ChevronDown size={16} className={why ? 'rotate-180' : ''} aria-hidden /></button>
            {why && <p className="border-t border-line px-3 py-2 text-sub">{ai
              ? 'This suggestion was generated by an AI model reading the code. It is a hypothesis, may be incorrect, and has not been confirmed by a tool or a test.'
              : `${f.tool} reported rule ${f.ruleId} at this line. The tool matches code patterns, so it can produce false positives. Review the evidence before acting.`}</p>}
          </div>
          <p className="text-xs text-mute">Demonstration data. No real analysis produced this finding.</p>
        </div>
      </div>
    </aside></div>
}
